  await evaluate("location.hash='#/';scrollTo({top:0,behavior:'instant'})");
  await click('.hero-actions [data-new-event]');await waitFor("!document.getElementById('creation-view').hidden");
  await values({'brief-description':'A garden wedding'});await click('#brief-extract');
  await waitFor("!document.getElementById('brief-result').hidden");
