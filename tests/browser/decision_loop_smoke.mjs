  assert(await evaluate("document.getElementById('brief-use').hidden"));
  await send('Network.setBlockedURLs',{urls:['*/api/intake']});
  await values({'brief-description':'A garden wedding for 120 guests'});await click('#brief-extract');
  await waitFor("!document.getElementById('brief-error').hidden");
  assert.equal(await evaluate("document.getElementById('brief-description').value"),'A garden wedding for 120 guests');
  await send('Network.setBlockedURLs',{urls:[]});
  const day=await evaluate("(()=>{const d=new Date();d.setDate(d.getDate()+120);return d.toLocaleDateString('en-CA')})()");
  await values({'brief-description':`A wedding in Mumbai on ${day} for 120 guests with a budget of INR 800000. Theme: <img src=x onerror=alert(1)>`});
  await click('#brief-extract');await waitFor("!document.getElementById('brief-use').hidden");
  assert.equal(await evaluate("document.querySelectorAll('#brief-result img').length"),0);
  assert(await evaluate("document.getElementById('brief-result').textContent.includes('BUILT-IN EXTRACTION')"));
  assert.deepEqual(await evaluate("fetch('/api/events').then(r=>r.json())"),before);
  await values({'brief-description':`A wedding in Mumbai on ${day} for 120 guests with a budget of INR 800000. Theme: candlelit garden`});
  assert(await evaluate("document.getElementById('brief-use').hidden"));
  await click('#brief-extract');await waitFor("!document.getElementById('brief-use').hidden");
  await evaluate("document.getElementById('brief-result').scrollIntoView({block:'start',behavior:'instant'})");
  await capture('event-brief-desktop');
  await viewport(390);await evaluate("document.getElementById('brief-result').scrollIntoView({block:'center',behavior:'instant'})");
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'));
  await capture('event-brief-mobile');await viewport(1440);
  await click('#brief-use');assert.equal(await evaluate("document.getElementById('wizard-position').textContent"),'5 / 5');
