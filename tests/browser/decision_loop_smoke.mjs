  assert.equal(planned.plan.budget_lines.reduce((total,line)=>total+line.amount,0),800000);
  await evaluate("location.hash='#/';scrollTo({top:0,behavior:'instant'});window.__decisionConfirm=window.confirm;window.confirm=()=>true");
